// Гитарист «по аккордам плана» (блок gtrnotes): подсказка под звуком — партия строится по аккордам плана трека и
// ударам его гитары, поэтому треку нужен план (транскрипция). Чистая логика без DOM.

/** chain — цепочка блоков; t — перевод. Нет блока gtrnotes — ''. */
export function notesHint(chain, t) {
  return (chain || []).some((b) => b && b.type === 'gtrnotes') ? t('gnotes.plan') : ''
}
